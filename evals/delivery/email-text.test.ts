import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { callTool } from "@/lib/tools/registry.ts";
import {
  buildEmailReportText,
  emailVerdictLine,
  EMAIL_TEXT_FINDINGS_CAP,
  SIMULATED_BANNER,
} from "@/lib/delivery/email-text.ts";
import { detectInjectionSignatures } from "@/lib/crew/injection-scan.ts";

/**
 * L-2 PLAIN-TEXT EMAIL BODY — byte-frozen goldens for the half that a live send
 * actually transmits (2026-07-25).
 *
 * WHY THIS FILE EXISTS: the L-2 Resend one-shot POSTs both a `text` and an
 * `html` half. The `html` half has always been built by the golden-tested
 * `buildEmailReportHtml`, and the sibling Slack one-shot imports
 * `buildSlackReportPayload` — but the `text` half was composed INLINE inside the
 * script, pinned by no golden and no assertion. It was therefore the ONLY
 * live-send surface in the repo whose exact bytes no test observed: a copy edit
 * there would have reached a real inbox with nothing objecting.
 *
 * A capability sweep found the gap; `lib/delivery/email-text.ts` closed it. The
 * extraction was proven byte-identical to the prior inline composition (1519
 * bytes both ways on the drifted fixture) before these goldens were minted, so
 * the goldens freeze the SHIPPED wire format, not a new one.
 *
 * The goldens are generated BY THE REAL BUILDER and never hand-edited — the
 * repo-wide rule. Regenerating is a reviewed diff, not a convenience.
 */

const GOLD = join(process.cwd(), "evals", "delivery", "gold");
const SITE_LINK = "https://curbside-commons.pages.dev/fees";
const DRIFTED = "fixtures/synthetic-restaurant/fees/statement.drifted.json";
const FAITHFUL = "fixtures/synthetic-restaurant/fees/statement.faithful.json";

const driftedCanonical = callTool("audit_statement", { statementPath: DRIFTED }).canonical;
const passCanonical = callTool("audit_statement", { statementPath: FAITHFUL }).canonical;

describe("L-2 email text builder — byte-frozen goldens", () => {
  const cases = [
    { name: "email-text-fees-drifted", canonical: driftedCanonical },
    { name: "email-text-fees-pass", canonical: passCanonical },
  ] as const;

  for (const c of cases) {
    it(`${c.name}: byte-identical to the committed golden`, () => {
      const body = buildEmailReportText(c.canonical, { siteLink: SITE_LINK });
      expect(body).toBe(readFileSync(join(GOLD, `${c.name}.golden.txt`), "utf8"));
    });
  }

  it("deterministic: building twice yields identical bytes", () => {
    expect(buildEmailReportText(driftedCanonical, { siteLink: SITE_LINK })).toBe(
      buildEmailReportText(driftedCanonical, { siteLink: SITE_LINK }),
    );
  });
});

describe("L-2 email text builder — the A3 delivery invariants", () => {
  const body = buildEmailReportText(driftedCanonical, { siteLink: SITE_LINK });

  it("control #4: the SIMULATED banner is the FIRST content of the body", () => {
    expect(body.startsWith(SIMULATED_BANNER)).toBe(true);
  });

  it("the verdict headline leads the content, before any finding", () => {
    const verdict = body.indexOf("Result:");
    const firstFinding = body.indexOf("\n- ");
    expect(verdict).toBeGreaterThan(-1);
    expect(firstFinding).toBeGreaterThan(verdict);
  });

  it("A3 boundary: the module carries NO url literal — the link is caller-supplied", () => {
    const src = readFileSync(join(process.cwd(), "lib", "delivery", "email-text.ts"), "utf8");
    // The builder must never be able to name an endpoint. Only the caller can.
    expect(src).not.toMatch(/https?:\/\/[a-z0-9.-]+\.[a-z]{2,}/i);
    expect(buildEmailReportText(driftedCanonical, { siteLink: "https://example.test/x" })).toContain(
      "https://example.test/x",
    );
  });

  it("truncation is EXPLICIT, never silent, and only past the cap", () => {
    const many = JSON.stringify({
      ok: false,
      findings: Array.from({ length: EMAIL_TEXT_FINDINGS_CAP + 3 }, (_, i) => ({
        verdict: "violation",
        ruleId: `RULE-${i}`,
        plainLine: `line ${i}`,
      })),
    });
    const truncated = buildEmailReportText(many, { siteLink: SITE_LINK });
    expect(truncated).toContain("...and 3 more findings — the full set travels in the attached report.json.");
    expect(truncated).toContain("line 5");
    expect(truncated).not.toContain("line 6"); // past the cap, carried by report.json
    // At exactly the cap there is no remainder row at all.
    const exact = JSON.stringify({
      ok: false,
      findings: Array.from({ length: EMAIL_TEXT_FINDINGS_CAP }, (_, i) => ({
        verdict: "violation",
        ruleId: `R${i}`,
        plainLine: `l${i}`,
      })),
    });
    expect(buildEmailReportText(exact, { siteLink: SITE_LINK })).not.toContain("...and");
  });

  it("refuses a canonical that is not a decision-grade report (never emits a weaker body)", () => {
    expect(() => buildEmailReportText("{}", { siteLink: SITE_LINK })).toThrow(/decision-grade/);
    expect(() => buildEmailReportText(JSON.stringify({ ok: true }), { siteLink: SITE_LINK })).toThrow(/decision-grade/);
  });

  it("the verdict line is ONE definition, shared with the subject (no second inline copy)", () => {
    // The drift this extraction exists to prevent: subject and body disagreeing.
    expect(body).toContain(`Result: ${emailVerdictLine(false, 5, 5)}`);
    expect(emailVerdictLine(true, 0, 0)).toBe("PASS — no violations (0 non-gating findings)");
    expect(emailVerdictLine(false, 1, 1)).toBe("FAIL — 1 violation across 1 finding");
  });

  it("honesty (RULES §4): simulated-labelled, no real-platform or real-merchant claim", () => {
    expect(body).toContain("SIMULATED DATA");
    expect(body).toContain("No real platform access.");
    expect(body).toMatch(/Simulated data checked against real NYC law/);
    for (const brand of ["DoorDash", "Uber Eats", "Grubhub", "Square", "Toast"]) {
      expect(body).not.toContain(brand);
    }
  });

  /**
   * Cross-check with the M2 tripwire: the product must never trip its own
   * injection scan. This body is a live-send surface, so it gets the same
   * property test the other generators get (`M2-SELF`).
   */
  it("the text half never trips the injection tripwire (M2-SELF property)", () => {
    expect(detectInjectionSignatures(body)).toEqual([]);
    expect(detectInjectionSignatures(buildEmailReportText(passCanonical, { siteLink: SITE_LINK }))).toEqual([]);
  });
});

/**
 * The PASS body's empty-findings region renders as consecutive blank lines
 * (there are no finding rows to place between the verdict and the evidence
 * pointer). That is COSMETIC and it is what currently ships — pinned here so the
 * shape is a deliberate, visible decision rather than an accident, and so any
 * future tidy-up is a reviewed golden diff instead of a silent wire change.
 */
describe("L-2 email text builder — the PASS empty state, pinned as-is", () => {
  const pass = buildEmailReportText(passCanonical, { siteLink: SITE_LINK });

  it("carries the count-free PASS verdict (no fabricated denominator)", () => {
    // The session-33 adjudication: the canonical exposes no reviewed-line count,
    // so the honest wording states the verdict without inventing a rate.
    expect(pass).toContain("Result: PASS — no violations (0 non-gating findings)");
    // Scope the no-denominator check to the VERDICT LINE. A body-wide
    // /\d+\s*(of|\/)\s*\d+/ matched the statutory citation "Local Law 79 of
    // 2025" — a false positive of exactly the shape this session spent its
    // effort removing from the injection scan: a pattern with no context
    // requirement. Assert on the region that can actually carry a rate.
    const verdictLine = pass.split("\n").find((l) => l.startsWith("Result:")) ?? "";
    expect(verdictLine).not.toMatch(/\d+\s*(of|\/|out of)\s*\d+/);
    expect(verdictLine).not.toMatch(/\d+\s*%/);
  });

  it("renders no finding rows and no truncation row", () => {
    expect(pass).not.toContain("\n- ");
    expect(pass).not.toContain("...and");
  });

  it("KNOWN COSMETIC: the empty findings region leaves an extra blank line", () => {
    // Documented, not hidden. If this is ever tidied, this assertion is the
    // reminder that it changes bytes a live send transmits.
    expect(pass).toContain("(0 non-gating findings)\n\n\nAttached report.json");
  });
});
