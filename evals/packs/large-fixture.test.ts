/** LST-HOURS-WINDOW count for one committed day under a given sync-lag allowance (the check alone, over every claim). */
function hoursCount(day: number, grace?: number): number {
  const claims = acpFeedToClaims(feed(day));
  const detector = grace === undefined ? hoursWindowDetector() : hoursWindowDetector(grace);
  return verifyClaims(claims, sorReference(record()), [detector]).filter((f) => f.ruleId === "LST-HOURS-WINDOW").length;
}

describe("GRACE — HOURS_WINDOW_GRACE_MINUTES is a parameter that defaults to the exported constant", () => {
  it("the exported constant is still fifteen minutes and the manifest records it", () => {
    expect(HOURS_WINDOW_GRACE_MINUTES).toBe(15);
    expect(manifest().engine.hoursWindowGraceMinutes).toBe(HOURS_WINDOW_GRACE_MINUTES);
  });

  it("the default grace is the constant: the bare detector, the explicit constant and the engine's own list agree", () => {
    for (const day of DAY_NUMBERS) {
      const engineCount = manifest().days[day - 1].byRuleId["LST-HOURS-WINDOW"] ?? 0;
      expect(hoursCount(day)).toBe(engineCount);
      expect(hoursCount(day, HOURS_WINDOW_GRACE_MINUTES)).toBe(engineCount);
    }
    const viaList = verifyClaims(acpFeedToClaims(feed(7)), sorReference(record()), listingsDetectors).filter((f) => f.ruleId === "LST-HOURS-WINDOW").length;
    expect(viaList).toBe(hoursCount(7));
  });

  it("a tighter allowance finds more, a looser one finds fewer, on the large fixture (derived on both sides)", () => {
    const def = hoursCount(7);
    const tight = hoursCount(7, 5);
    const loose = hoursCount(7, 30);
    expect(def).toBeGreaterThan(0);
    expect(tight, "grace 5 vs default").toBeGreaterThan(def);
    expect(loose, "grace 30 vs default").toBeLessThan(def);
    expect(hoursCount(7, 0)).toBeGreaterThanOrEqual(tight);
    expect(hoursCount(7, 600)).toBe(0);
  });
});
