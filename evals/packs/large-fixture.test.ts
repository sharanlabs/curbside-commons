const round = (n: number, places: number): number => Math.round(n * 10 ** places) / 10 ** places;

describe("DERIVED — alert-volume figures recomputed from the engine on the committed files", () => {
  it.each(DAY_NUMBERS)("day %i: findings, errors, warnings, by-rule tally, per-100 and warn share equal the manifest", (day) => {
    const m = manifest();
    const row = m.days[day - 1];
    expect(row.day).toBe(day);
    const items = record().items.length;
    const findings = engine(day).findings;
    const tally: Record<string, number> = {};
    for (const f of findings) tally[f.ruleId] = (tally[f.ruleId] ?? 0) + 1;
    const errors = findings.filter((f) => f.severity === "error").length;
    const warns = findings.filter((f) => f.severity === "warn").length;
    expect(row.findings).toBe(findings.length);
    expect(row.errors).toBe(errors);
    expect(row.warnings).toBe(warns);
    expect(errors + warns).toBe(findings.length);
    expect(row.byRuleId).toEqual(tally);
    expect(Object.values(row.byRuleId).reduce((a, b) => a + b, 0)).toBe(row.findings);
    expect(row.findingsPer100Items).toBe(round((findings.length / items) * 100, 2));
    expect(row.warnShare).toBe(findings.length === 0 ? 0 : round(warns / findings.length, 4));
  });

  it("the series is non-empty on every day and never shrinks (drift accumulates; nothing is corrected)", () => {
    const counts = manifest().days.map((d) => d.findings);
    counts.forEach((c) => expect(c).toBeGreaterThan(0));
    counts.slice(1).forEach((c, i) => expect(c).toBeGreaterThanOrEqual(counts[i]));
  });

  it("the series exercises the warning rules and the error rules", () => {
    const last = manifest().days[DAY_NUMBERS.length - 1];
    expect(last.warnings).toBeGreaterThan(0);
    expect(last.errors).toBeGreaterThan(0);
    for (const rule of ["LST-PRICE-VALUE", "LST-AVAIL-STATE", "LST-MOD-PRICE-VALUE", "LST-MOD-MISSING", "LST-HOURS-WINDOW"]) {
      expect(Object.keys(last.byRuleId), rule).toContain(rule);
    }
  });

  it("the drift applied each day equals the difference between consecutive committed feeds", () => {
    const r = record();
    let prev: AcpFeed = buildFaithfulMenuFeed(r);
    const modOf = (row: AcpFeedItem) => new Map((row.modifiers ?? []).map((m) => [m.id, m.price_delta]));
    for (const day of DAY_NUMBERS) {
      const cur = feed(day);
      const before = new Map(prev.items.map((row) => [row.item_id, row]));
      const got = { price: 0, availability: 0, title: 0, modifierPrice: 0, modifierDrop: 0, hours: 0 };
      expect(cur.items.map((x) => x.item_id)).toEqual(prev.items.map((x) => x.item_id));
      for (const row of cur.items) {
        const p = before.get(row.item_id)!;
        if (row.price !== p.price) got.price++;
        if (row.availability !== p.availability) got.availability++;
        if (row.title !== p.title) got.title++;
        if (row.hours !== undefined && JSON.stringify(row.hours) !== JSON.stringify(p.hours)) got.hours++;
        const pm = modOf(p);
        const cm = modOf(row);
        for (const [id, price] of pm) {
          if (!cm.has(id)) got.modifierDrop++;
          else if (cm.get(id) !== price) got.modifierPrice++;
        }
      }
      expect(manifest().days[day - 1].driftApplied, `day ${day}`).toEqual(got);
      prev = cur;
    }
  });

  it("the declared rates in the manifest are the generator's constants", async () => {
    const g = await gen();
    expect(manifest().assumptions.ratesPerDay).toEqual({ ...g.DRIFT_RATES });
    expect(manifest().seed).toBe(g.LARGE_SEED);
  });
});

