/**
 * LARGE SYNTHETIC RESTAURANT — Wave 3 lane W3-d (docs/plan-wave3-2026-10-31.md § 1 item 6).
 *
 * fixtures/synthetic-restaurant-large/ = record.json · feeds/day-01..07.json · manifest.json · README.md,
 * generated by ONE script (scripts-ts/generate-large-fixture.mts) at its own seed. Pattern: scenarios.test.ts.
 *
 *  FREEZE   regenerate in memory and byte-compare every committed file; the committed file set IS the
 *           generated file set. One byte edited -> red -> run the generator -> green.
 *  DERIVED  the EXISTING engine is run here on the COMMITTED files (parsed from disk, not from the generator's
 *           in-memory objects) and the manifest's per-day figures — findings, errors, warnings, by-rule tally,
 *           findings per 100 items, warn share, and the drift applied — are re-derived by code written in THIS
 *           file, independently of the generator's own derivation.
 *  README   every figure is a {{placeholder}} the script fills; this file re-derives the figures and fills the
 *           template itself. A digit typed outside the placeholders is red.
 *  SCALE    the item count sits inside the band the generator declares (not a literal here).
 *  GRACE    the hours check's sync-lag allowance is a parameter that defaults to the exported 15 minutes; a
 *           different allowance on the large fixture changes the LST-HOURS-WINDOW count (derived on both sides).
 *
 * ── Proof record (2026-10-31; commands + outputs are in docs/returns/2026-10-31-w3d-large-fixture.md) ──
 *  See the return packet: the planted README mutation (a figure typed over its placeholder) and the
 *  one-byte feed edit, each with its red and its restore.
 */

const ROOT = process.cwd();
const DIR = join(ROOT, "fixtures", "synthetic-restaurant-large");
const read = (p: string): string => readFileSync(p, "utf8");
const readJson = <T,>(rel: string): T => JSON.parse(read(join(DIR, rel))) as T;
const gen = () => import("@/scripts-ts/generate-large-fixture.mts");

/** Every file under a folder, as sorted posix paths relative to `base`. */
function listFiles(dir: string, base = dir): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) out.push(...listFiles(full, base));
    else out.push(relative(base, full).split("\\").join("/"));
  }
  return out.sort();
}

interface DayRow {
  day: number;
  file: string;
  driftApplied: Record<string, number>;
  findings: number;
  errors: number;
  warnings: number;
  byRuleId: Record<string, number>;
  findingsPer100Items: number;
  warnShare: number;
}
interface Manifest {
  seed: number;
  asOf: string;
  engine: { hoursWindowGraceMinutes: number };
  counts: Record<string, number>;
  itemBand: { target: number; min: number; max: number };
  assumptions: { ratesPerDay: Record<string, number> };
  days: DayRow[];
}

const record = (): SyntheticCatalog => readJson<SyntheticCatalog>("record.json");
const feed = (day: number): AcpFeed => readJson<AcpFeed>(`feeds/day-${String(day).padStart(2, "0")}.json`);
const manifest = (): Manifest => readJson<Manifest>("manifest.json");
const DAY_NUMBERS = [1, 2, 3, 4, 5, 6, 7] as const;

/** Independent engine run on a committed day. */
function engine(day: number) {
  return runListingsVerification(acpFeedToClaims(feed(day)), record());
}

