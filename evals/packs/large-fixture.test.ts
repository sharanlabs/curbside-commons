const BANNED_REGISTER = /\b(sample|demo|example|real)s?\b/i;
const NAMED_REAL_PARTIES = /\b(DoorDash|Uber\s?Eats|Uber|Grubhub|Instacart|Square|Toast|Deliverect|Gemini|ChatGPT|OpenAI|Anthropic|Claude|Google|Postmates)\b/i;
/** The only digit-bearing tokens the README may type: the feed file names. */
const ALLOWED_TYPED_TOKENS = /day-0\d/g;
const typedDigits = (text: string): string[] => text.replace(ALLOWED_TYPED_TOKENS, " ").match(/\d/g) ?? [];

/** Fill a template with figures — a deliberately separate, tiny implementation. */
function fill(template: string, figures: Record<string, string | number>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_m, key: string) => {
    if (!(key in figures)) throw new Error(`placeholder {{${key}}} has no figure`);
    return String(figures[key]);
  });
}
const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
function capture(template: string, text: string): { keys: string[]; values: string[] } | null {
  const parts = template.split(/\{\{(\w+)\}\}/);
  const keys: string[] = [];
  let re = "^";
  parts.forEach((p, i) => {
    if (i % 2 === 0) re += escapeRe(p);
    else {
      keys.push(p);
      re += "([^\\n]+?)";
    }
  });
  re += "$";
  const m = new RegExp(re).exec(text);
  return m ? { keys, values: m.slice(1) } : null;
}

/** The README's figures, derived HERE from the engine run on the committed files and the record. */
function liveFigures(): Record<string, string | number> {
  const r = record();
  const m = manifest();
  const variations = r.items.flatMap((i) => i.variations);
  const items = r.items.length;
  const f: Record<string, string | number> = {
    items,
    categories: new Set(r.items.map((i) => i.category)).size,
    variations: variations.length,
    feed_rows: variations.filter((v) => v.stock !== "hidden").length,
    groups: r.items.reduce((n, i) => n + i.modifierLists.length, 0),
    options: r.items.reduce((n, i) => n + recordModifierOptions(i).length, 0),
    days: DAY_NUMBERS.length,
    seed: m.seed,
    as_of: r.asOf,
    grace: HOURS_WINDOW_GRACE_MINUTES,
    rate_price: `${(m.assumptions.ratesPerDay.price * 100).toFixed(1)}%`,
    rate_availability: `${(m.assumptions.ratesPerDay.availability * 100).toFixed(1)}%`,
    rate_title: `${(m.assumptions.ratesPerDay.title * 100).toFixed(1)}%`,
    rate_modifier_price: `${(m.assumptions.ratesPerDay.modifierPrice * 100).toFixed(1)}%`,
    rate_modifier_drop: `${(m.assumptions.ratesPerDay.modifierDrop * 100).toFixed(1)}%`,
    rate_hours: `${(m.assumptions.ratesPerDay.hours * 100).toFixed(1)}%`,
  };
  let lastPer100 = "";
  let lastShare = "";
  for (const day of DAY_NUMBERS) {
    const findings = engine(day).findings;
    const tally = new Map<string, number>();
    for (const x of findings) tally.set(x.ruleId, (tally.get(x.ruleId) ?? 0) + 1);
    const warns = findings.filter((x) => x.severity === "warn").length;
    const p = `d0${day}`;
    f[`${p}_findings`] = findings.length;
    f[`${p}_errors`] = findings.filter((x) => x.severity === "error").length;
    f[`${p}_warnings`] = warns;
    f[`${p}_per100`] = round((findings.length / items) * 100, 2).toFixed(2);
    f[`${p}_warn_share`] = `${(round(warns / findings.length, 4) * 100).toFixed(1)}%`;
    f[`${p}_rules`] = [...tally.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([k, n]) => `${k} ×${n}`).join(", ");
    lastPer100 = String(f[`${p}_per100`]);
    lastShare = String(f[`${p}_warn_share`]);
  }
  f.last_per100 = lastPer100;
  f.last_warn_share = lastShare;
  return f;
}

describe("README — structure, derived figures, register, honesty", () => {
  const readme = (): string => read(join(DIR, "README.md"));

  it("the README equals the template filled with figures derived in this file", async () => {
    const g = await gen();
    const text = readme();
    expect(text).not.toContain("{{");
    const live = liveFigures();
    expect(text).toBe(fill(g.README_TEMPLATE, live));
    const cap = capture(g.README_TEMPLATE, text);
    expect(cap, "the committed README no longer matches its template (typed edit?)").not.toBeNull();
    cap!.keys.forEach((k, i) => expect(cap!.values[i], `{{${k}}}`).toBe(String(live[k])));
  });

  it("no digit is typed by hand — only the feed file names appear outside placeholders", async () => {
    const g = await gen();
    expect(typedDigits(g.README_TEMPLATE.replace(/\{\{\w+\}\}/g, " ")), "the template types digits").toEqual([]);
    let masked = readme().replace(ALLOWED_TYPED_TOKENS, " ");
    for (const v of Object.values(liveFigures()).map(String).sort((a, b) => b.length - a.length)) masked = masked.split(v).join(" ");
    expect(typedDigits(masked), "README.md has a typed digit").toEqual([]);
  });

  it("the register and honesty probes bite in isolation", () => {
    expect(typedDigits("the copy shows 3 items")).toEqual(["3"]);
    expect(typedDigits("see day-01 and day-07")).toEqual([]);
    expect(BANNED_REGISTER.test("a bundled sample menu")).toBe(true);
    expect(BANNED_REGISTER.test("real merchant data")).toBe(true);
    expect(BANNED_REGISTER.test("a synthetic restaurant")).toBe(false);
    expect(NAMED_REAL_PARTIES.test("a menu on DoorDash")).toBe(true);
  });

  it("production register, honesty labels and the assumption statement hold", () => {
    const text = readme();
    expect(text).not.toMatch(BANNED_REGISTER);
    expect(text).not.toMatch(NAMED_REAL_PARTIES);
    expect(text).toMatch(/\bsynthetic\b/i);
    expect(text).toMatch(/\bsimulated\b/i);
    expect(text).toMatch(/declared assumption/i);
    expect(text).toMatch(/assumptions we set/i);
    for (const banned of [/\bno AI was used\b/i, /\bAI built this\b/i, /\bwe have (?:real |live )?(?:platform |marketplace )?access\b/i]) {
      expect(banned.test(text)).toBe(false);
    }
  });
});

