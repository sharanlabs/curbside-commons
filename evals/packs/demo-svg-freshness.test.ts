import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * DEMO SVG FRESHNESS — the README's hero image must still be what the CLI
 * actually prints (added 2026-07-26, capability-sweep CLI finding).
 *
 * WHY: `README.md` says the image is *"the demo's real captured output —
 * rendered line-for-line from a live `node bin/check.mjs demo` run, never
 * staged."* That is a PROVENANCE claim, and it had quietly gone false. The
 * D4 vocabulary slice renamed "serving copy" → "the feed" through the engine and
 * regenerated every golden — but `docs/assets/demo.svg` is not a golden, nothing
 * compared it to anything, and it kept showing the retired wording on the
 * project's most-looked-at surface for days.
 *
 * The gap was structural, not careless: every OTHER derived artifact here is
 * pinned by a byte-comparison, so drift fails a test. This one was generated by
 * a script that nobody re-ran and nothing checked. **A derived artifact with no
 * comparison is not derived — it is a copy that was once accurate.**
 *
 * This test does not re-render (that would write into the repo during a test
 * run). It asserts the weaker, sufficient property: every line of text the live
 * demo prints appears verbatim in the committed SVG. That catches vocabulary
 * drift, dropped beats, and changed verdicts — the ways this file can lie —
 * without coupling to the renderer's layout or byte format.
 */

const ROOT = process.cwd();
const SVG = join(ROOT, "docs", "assets", "demo.svg");

/** Strip ANSI colour codes the terminal capture may carry. */
function stripAnsi(s: string): string {
  return s.replace(/\[[0-9;]*m/g, "");
}

/** XML-unescape the SVG's text nodes so they compare against raw CLI output. */
function unescapeXml(s: string): string {
  return s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&");
}

describe("demo SVG — the README's hero image is a CURRENT capture, not a stale one", () => {
  const svg = readFileSync(SVG, "utf8");
  const svgText = unescapeXml([...svg.matchAll(/<text[^>]*>([\s\S]*?)<\/text>/g)].map((m) => m[1]).join("\n"));

  const live = stripAnsi(
    execFileSync("node", [join(ROOT, "bin", "check.mjs"), "demo"], { cwd: ROOT, encoding: "utf8", timeout: 60_000 }),
  );

  it("the live demo actually produced output (the comparison is not vacuous)", () => {
    expect(live.split("\n").filter((l) => l.trim() !== "").length).toBeGreaterThan(20);
    expect(svgText.length).toBeGreaterThan(500);
  });

  it("every non-trivial line the live demo prints appears in the committed SVG", () => {
    const liveLines = live
      .split("\n")
      .map((l) => l.trimEnd())
      .filter((l) => l.trim().length > 12); // skip rules/blanks/short separators
    const missing = liveLines.filter((l) => !svgText.includes(l.trim()));
    expect(
      missing,
      `docs/assets/demo.svg is STALE — regenerate it with \`node scripts-ts/render-demo-svg.mts\`.\n` +
        `Lines the live demo prints that the committed image does not show:\n` +
        missing.map((l) => `  ${l.trim()}`).join("\n"),
    ).toEqual([]);
  });

  it("carries no RETIRED vocabulary (the specific drift that went unnoticed)", () => {
    // "serving copy" was renamed to "the feed" in the D4 slice. The engine and
    // every golden were regenerated; this image was not, and nothing noticed.
    expect(svgText).not.toContain("serving copy");
  });

  it("still carries its simulated labelling (RULES §4 rides the hero image too)", () => {
    expect(svgText).toMatch(/simulated/i);
  });
});
